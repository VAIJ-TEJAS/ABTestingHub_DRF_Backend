from django.contrib.auth.models import User
from django.db import models


class Test(models.Model):
    user = models.ForeignKey(User, on_delete=models.SET_NULL, null=True)
    name = models.CharField(max_length=255)
    description = models.TextField(blank=True, null=True)
    hypotheses = models.TextField(blank=True, null=True)
    primary_metric = models.CharField(max_length=255, blank=True, null=True)
    business_target = models.CharField(max_length=255, blank=True, null=True)
    no_of_arms = models.IntegerField()
    proportional_metric = models.BooleanField()
    start_date = models.DateField(blank=True, null=True)

    confidence_level = models.FloatField(blank=True, null=True)
    power = models.FloatField(blank=True, null=True)
    baseline_conversion_rate = models.FloatField(blank=True, null=True)
    baseline_kpi = models.FloatField(blank=True, null=True)
    kpi_sd = models.FloatField(blank=True, null=True)
    mde = models.FloatField(blank=True, null=True)
    absolute = models.BooleanField(blank=True, null=True)
    daily_interactions = models.IntegerField(blank=True, null=True)
    expected_uplift = models.FloatField(blank=True, null=True)
    equal_allocation = models.BooleanField(blank=True, null=True)
    two_tailed_test = models.BooleanField(blank=True, null=True)
    revenue_per_unit_kpi = models.FloatField(blank=True, null=True)
    total_sample_size = models.IntegerField(blank=True, null=True)
    sample_size_per_arm = models.IntegerField(blank=True, null=True)
    days_required = models.IntegerField(blank=True, null=True)
    weeks_required = models.IntegerField(blank=True, null=True)
    control_revenue = models.FloatField(blank=True, null=True)
    test_revenue = models.FloatField(blank=True, null=True)

    visitors_group_a = models.IntegerField(blank=True, null=True)
    conversions_group_a = models.IntegerField(blank=True, null=True)
    visitors_group_b = models.IntegerField(blank=True, null=True)
    conversions_group_b = models.IntegerField(blank=True, null=True)
    visitors_group_c = models.IntegerField(blank=True, null=True)
    conversions_group_c = models.IntegerField(blank=True, null=True)
    visitors_group_d = models.IntegerField(blank=True, null=True)
    conversions_group_d = models.IntegerField(blank=True, null=True)
    visitors_group_e = models.IntegerField(blank=True, null=True)
    conversions_group_e = models.IntegerField(blank=True, null=True)
    conversion_rate_a = models.FloatField(blank=True, null=True)
    conversion_rate_b = models.FloatField(blank=True, null=True)
    test_statistic = models.FloatField(blank=True, null=True)
    p_value_b = models.FloatField(blank=True, null=True)
    ci_lower_bound = models.FloatField(blank=True, null=True)
    ci_upper_bound = models.FloatField(blank=True, null=True)
    conversion_rate_c = models.FloatField(blank=True, null=True)
    conversion_rate_d = models.FloatField(blank=True, null=True)
    conversion_rate_e = models.FloatField(blank=True, null=True)
    relative_uplift_in_cr_c = models.FloatField(blank=True, null=True)
    relative_uplift_in_cr_d = models.FloatField(blank=True, null=True)
    relative_uplift_in_cr_e = models.FloatField(blank=True, null=True)
    p_value_c = models.FloatField(blank=True, null=True)
    p_value_d = models.FloatField(blank=True, null=True)
    p_value_e = models.FloatField(blank=True, null=True)
    disclaimer_note = models.TextField(blank=True, null=True)
    statistically_significant = models.BooleanField(blank=True, null=True)

    test_status = models.CharField(max_length=15, blank=True, null=True)
    test_integrity = models.CharField(max_length=15, blank=True, null=True)
    last_modified_date = models.DateField(null=True, blank=True)

    def __str__(self):
        return self.name
